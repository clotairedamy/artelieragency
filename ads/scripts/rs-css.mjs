// Builds the Rust kit's stylesheets from the Vue kit, so the two cannot drift.
//
//   node scripts/rs-css.mjs          write ads-rs/assets/css/*
//   node scripts/rs-css.mjs --check  lint only, exit 1 on a violation
//
// The four shared sheets are copied byte for byte. components.css is every
// Vue component's scoped style, de-scoped — which is only safe because of the
// naming rule this script enforces: a component's own classes are
// `ads-<name>` for its root and `ads-<name>__<part>` for everything inside,
// with `is-<state>` modifiers. `__` never appears in the global layer, so no
// two components (and no component and the layer) can claim the same class.
// Before this rule, de-scoping let `.body`, `.section` and `.title` from a
// dozen components overwrite each other and the base primitives.
import { readFileSync, writeFileSync, readdirSync, copyFileSync } from 'node:fs'
import { join, basename, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const vueDir = join(root, 'app/components')
const cssDir = join(root, 'app/assets/css')
const rsCss = join(root, 'ads-rs/assets/css')
const shared = ['tokens.css', 'base.css', 'ads.css', 'ads-utility.css']
const check = process.argv.includes('--check')

/** AdsInputOtp → ads-input-otp, HeroSection → ads-hero-section. */
export function prefixOf(name) {
  const kebab = name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
  return kebab.startsWith('ads-') ? kebab : `ads-${kebab}`
}

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '')

/** Replace `:deep(x)`, `:slotted(x)` and `:global(x)` with `x`, parens balanced. */
function descope(css) {
  const re = /:(deep|slotted|global)\(/g
  let out = ''
  let last = 0
  let m
  while ((m = re.exec(css))) {
    let depth = 1
    let i = m.index + m[0].length
    while (i < css.length && depth) {
      if (css[i] === '(') depth++
      else if (css[i] === ')') depth--
      i++
    }
    out += css.slice(last, m.index) + css.slice(m.index + m[0].length, i - 1)
    last = i
    re.lastIndex = i
  }
  return out + css.slice(last)
}

/** Every class used in a selector, and every @keyframes name. */
function selectorsOf(css) {
  const classes = new Set()
  const keyframes = new Set()
  const text = stripComments(css)
  let depth = 0
  let skipUntil = -1
  let start = 0
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (ch === '{') {
      const prelude = text.slice(start, i).trim()
      if (skipUntil < 0) {
        if (prelude.startsWith('@')) {
          const kf = prelude.match(/^@(?:-webkit-)?keyframes\s+([\w-]+)/)
          if (kf) {
            keyframes.add(kf[1])
            skipUntil = depth
          }
        } else if (!/^[\w-]+\s*:/.test(prelude) || /[.#&>~+[\]]/.test(prelude)) {
          // A rule prelude rather than a nested declaration block.
          for (const c of prelude.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) classes.add(c[1])
        }
      }
      depth++
      start = i + 1
    } else if (ch === '}') {
      depth--
      if (skipUntil >= 0 && depth === skipUntil) skipUntil = -1
      start = i + 1
    } else if (ch === ';') {
      start = i + 1
    }
  }
  return { classes, keyframes }
}

const globals = new Set()
for (const f of shared) selectorsOf(readFileSync(join(cssDir, f), 'utf8')).classes.forEach((c) => globals.add(c))

const files = readdirSync(vueDir).filter((f) => f.endsWith('.vue')).sort()
const owners = new Map(files.map((f) => [prefixOf(basename(f, '.vue')), basename(f, '.vue')]))
const problems = []
let out = '/* ADS component styles — generated by scripts/rs-css.mjs from the Vue\n   components\' scoped styles. Do not edit by hand. */\n'

for (const file of files) {
  const name = basename(file, '.vue')
  const prefix = prefixOf(name)
  const src = readFileSync(join(vueDir, file), 'utf8')
  const blocks = [...src.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1])
  if (!blocks.length) continue
  const css = descope(blocks.join('\n')).trim()
  const { classes, keyframes } = selectorsOf(css)

  for (const c of classes) {
    if (c === prefix || c.startsWith(`${prefix}__`)) continue
    if (c.startsWith('is-') || globals.has(c)) continue
    const other = [...owners.keys()].find((p) => c === p || c.startsWith(`${p}__`))
    // A parent may style a child component's root (KpiRow spacing its
    // tiles); reaching into its parts would couple the two.
    if (other && c === other) continue
    problems.push(`${file}: .${c}${other ? ` belongs to ${owners.get(other)}` : ` is not ${prefix} / ${prefix}__* / is-* / global`}`)
  }
  for (const k of keyframes) {
    if (!k.startsWith(prefix)) problems.push(`${file}: @keyframes ${k} should start with ${prefix}`)
  }
  out += `\n/* ${file} */\n\n${css}\n`
}

if (problems.length) {
  console.error(`${problems.length} naming problem(s):\n  ${problems.join('\n  ')}`)
  if (check) process.exit(1)
}

if (!check) {
  for (const f of shared) copyFileSync(join(cssDir, f), join(rsCss, f))
  writeFileSync(join(rsCss, 'components.css'), out)
  console.log(`ads-rs/assets/css: ${shared.length} shared sheets copied, components.css from ${files.length} components`)
} else if (!problems.length) {
  console.log(`${files.length} components, no naming problems`)
}
